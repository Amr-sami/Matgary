/** F6 — structured ACTIVE CONTEXT block the model sees each turn. Kept compact
 *  so we don't blow the prompt budget; only the state that could matter for
 *  the next turn is included (last candidate set, selected entity, last
 *  write). The real IDs come from backend state — the model MUST use them
 *  verbatim; the F3 grounding guard still enforces this. */
function renderContextBlock(
  ctx: ConversationContext | null | undefined,
  resolved: RunDebug["referenceResolved"] | undefined,
  locale: Locale,
): string {
  if (!ctx) return "";
  const lines: string[] = [];
  lines.push(tr("context.header", locale));
  if (ctx.lastCandidateSet && ctx.lastCandidateSet.candidates.length > 0) {
    lines.push(
      tr("context.candidateHeader", locale, {
        n: ctx.lastCandidateSet.candidates.length,
        query: ctx.lastCandidateSet.query,
      }),
    );
    ctx.lastCandidateSet.candidates.forEach((c, i) => {
      const snap = c.snapshot ?? {};
      const bits = [
        `${i + 1}. ${c.displayName}`,
        `uuid=${c.entityId}`,
        snap.price != null ? `price=${snap.price} EGP` : null,
        snap.quantity != null ? `qty=${snap.quantity}` : null,
      ].filter(Boolean);
      lines.push(`  • ${bits.join(" · ")}`);
    });
  }
  if (ctx.selectedEntity) {
    const s = ctx.selectedEntity;
    lines.push(
      tr("context.selected", locale, { name: s.displayName, uuid: s.entityId }),
    );
  }
  if (ctx.recentWrites.length > 0) {
    const w = ctx.recentWrites[0]!;
    lines.push(
      tr("context.lastWrite", locale, {
        name: w.entityRef.displayName,
        field: w.field,
        before: String(w.before),
        after: String(w.after),
      }),
    );
  }
  if (resolved && resolved.kind === "resolved" && resolved.entityId) {
    lines.push(
      tr("context.hintResolved", locale, {
        uuid: resolved.entityId,
        reason: resolved.reason,
      }),
    );
  } else if (resolved && resolved.kind === "ambiguous") {
    lines.push(tr("context.hintAmbiguous", locale, { reason: resolved.reason }));
  }
  lines.push(tr("context.ruleUuid", locale));
  return "\n" + lines.join("\n");
}

/** Legacy export used by the route to classify error → HTTP shape. */
export function isTransientlyBusy(err: unknown): boolean {
  if (err instanceof ProviderError) {
    return (
      err.kind === "rate_limit" ||
      err.kind === "overloaded" ||
      err.kind === "timeout"
    );
  }
  const msg = err instanceof Error ? err.message : String(err);
  return /\b503\b|\b429\b|UNAVAILABLE|RESOURCE_EXHAUSTED|rate.?limit|overloaded|aborted/i.test(msg);
}

/* --------------------------------------------------- final blocks + salvage */

async function finalBlocks(
  buffered: AiBlock[],
  fallbackText: string,
  locale: Locale,
): Promise<AiBlock[]> {
  // Dedup the already-buffered blocks (should be a no-op given mergeDedup on
  // push, but defensive against future callers that push directly).
  if (buffered.length > 0) return dedupBlocks(buffered);
  // gpt-oss / some Gemini responses occasionally emit one or more render_* tool
  // call JSON objects as plain content instead of using the tool_calls channel.
  // Salvage them into proper AiBlocks so the mobile UI never shows raw JSON.
  // Dedup: a leaked JSON block that duplicates a prior round's render is
  // dropped (though in practice buffered.length === 0 here).
  const salvaged = await salvageLeakedRenderCalls(fallbackText);
  if (salvaged.length > 0) return dedupBlocks(salvaged);
  if (fallbackText.trim()) {
    // LAST LINE OF DEFENCE — salvage failed, content is non-empty. If the
    // content still looks like a structured leak (malformed JSON, half an
    // object, a tool-call that's not in our salvage map, …) we MUST NOT
    // ship it to the user as a chat bubble. Replace with a localised nudge
    // and log the original payload so engineers can diagnose.
    if (looksLikeStructuredLeak(fallbackText)) {
      console.warn("[ai/agent] structured JSON leak sanitised in final fallback", {
        preview: fallbackText.slice(0, 200),
      });
      return [{ kind: "text", text: sanitiseText(fallbackText, locale) }];
    }
    return [{ kind: "text", text: fallbackText }];
  }
  return [{ kind: "text", text: tr("nudge.noResult", locale) }];
}

const RENDER_TOOL_FOR_SALVAGE = {
  render_text: renderText,
  render_chart: renderChart,
  render_table: renderTable,
  render_kpi: renderKpi,
  render_product_card: renderProductCard,
  // Previously these six were NOT salvaged — the canSalvage regex named
  // them, so the agent would NOT nudge the model again, but the salvage
  // handler didn't recognise them either. The leaked JSON then fell through
  // to the raw-text fallback and the user saw `{"name":"render_warning",…}`
  // in a chat bubble. Covering them here closes that path.
  render_clarification: renderClarification,
  render_comparison: renderComparison,
  render_inventory_summary: renderInventorySummary,
  render_sales_summary: renderSalesSummary,
  render_warning: renderWarning,
  render_knowledge_answer: renderKnowledgeAnswer,
} as const;
type SalvageableName = keyof typeof RENDER_TOOL_FOR_SALVAGE;

interface LeakedCall {
  name: SalvageableName;
  args: Record<string, unknown>;
}

const SALVAGE_CTX: ToolContext = {
  tenantId: "",
  userId: "",
  role: null,
  permissions: [],
  locale: "en",
};

async function salvageLeakedRenderCalls(content: string): Promise<AiBlock[]> {
  // Expanded to match every render tool the model could leak. The previous
  // narrow allowlist caused salvage to silently refuse, and the content
  // then fell through to raw-text wrapping.
  if (
    !/render_(text|chart|table|kpi|product_card|clarification|comparison|inventory_summary|sales_summary|warning|knowledge_answer)/.test(
      content,
    )
  )
    return [];
  const calls: LeakedCall[] = [];
  for (const obj of iterateTopLevelJsonObjects(content)) {
    const call = parseLeakedCall(obj);
    if (call) calls.push(call);
  }
  if (calls.length === 0) {
    // Preview echoes raw model prose, which can repeat user-provided names /
    // amounts. Debug-gated so prod logs stay clean. Operators can still see
    // that the salvage path missed via the structured `[ai/run]` record.
    if (process.env.STORO_AI_DEBUG === "1") {
      console.warn(
        "[ai/agent] render_* mentioned but no salvage match",
        JSON.stringify({ preview: content.slice(0, 400) }),
      );
    }
    return [];
  }
  const results = await Promise.all(
    calls.map(async (c) => {
      try {
        return await RENDER_TOOL_FOR_SALVAGE[c.name].handler(SALVAGE_CTX, c.args);
      } catch {
        return null;
      }
    }),
  );
  const blocks: AiBlock[] = [];
  for (const r of results) {
    if (r && r.ok && "blocks" in r) blocks.push(...r.blocks);
  }
  return blocks;
}

function parseLeakedCall(objStr: string): LeakedCall | null {
  let parsed: Record<string, unknown>;
  try {
    parsed = JSON.parse(objStr) as Record<string, unknown>;
  } catch {
    return null;
  }
  const nameRaw =
    typeof parsed.type === "string"
      ? parsed.type
      : typeof parsed.name === "string"
        ? parsed.name
        : "";
  const name = nameRaw.replace(/[^a-z_].*$/, "");
  if (!(name in RENDER_TOOL_FOR_SALVAGE)) return null;
  const args =
    parsed.arguments && typeof parsed.arguments === "object" && parsed.arguments !== null
      ? (parsed.arguments as Record<string, unknown>)
      : stripDiscriminators(parsed);
  return { name: name as SalvageableName, args };
}

function stripDiscriminators(o: Record<string, unknown>): Record<string, unknown> {
  const { type: _t, name: _n, ...rest } = o;
  return rest;
}

function* iterateTopLevelJsonObjects(s: string): Generator<string> {
  let depth = 0;
  let start = -1;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === "{") {
      if (depth === 0) start = i;
      depth++;
    } else if (c === "}") {
      depth--;
      if (depth === 0 && start >= 0) {
        yield s.slice(start, i + 1);
        start = -1;
      }
    }
  }
}

