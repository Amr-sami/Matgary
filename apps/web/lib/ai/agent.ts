/**
 * AgentRunner — the provider-agnostic tool-call loop.
 *
 * Flow:
 *   1. Build the conversation with a locale-locked system prompt.
 *   2. Each round: call provider.chat({ system, messages, tools, … }).
 *   3. If the provider returned tool_calls:
 *      - execute each in parallel against the registry
 *      - render_* calls buffer AiBlocks for the final reply
 *      - data tool calls get their JSON appended as `tool` messages so the
 *        model can read it in the next round
 *      - loop again
 *   4. If no tool_calls: final answer.
 *      - if tools fetched data but no render_* fired AND content isn't
 *        salvageable JSON, nudge the model and loop once more
 *      - otherwise, salvage leaked render_* JSON from content, or wrap bare
 *        text, and return
 *   5. From round 2 onward, re-assert the locale directive so tool-JSON (full
 *      of English keys) doesn't drift the model out of Arabic.
 *
 * Hard caps:
 *   - MAX_ROUNDS: upper bound on tool-call iterations
 *   - MAX_RENDER_BLOCKS: never emit more than N UI blocks in one reply
 *   - MAX_RETRY_ATTEMPTS: per-call provider retries (transient only)
 */

const MAX_ROUNDS = 5;
const MAX_RENDER_BLOCKS = 8;

/** RFC-4122 v4 uuid using Math.random. Not cryptographic — turnId is an
 *  identity, not a secret. */
function mintTurnId(): string {
  const hex = "0123456789abcdef";
  const bytes: number[] = [];
  for (let i = 0; i < 16; i++) bytes.push(Math.floor(Math.random() * 256));
  bytes[6] = (bytes[6]! & 0x0f) | 0x40;
  bytes[8] = (bytes[8]! & 0x3f) | 0x80;
  const s = bytes.map((b) => hex[(b >> 4) & 0xf]! + hex[b & 0xf]!).join("");
  return `${s.slice(0, 8)}-${s.slice(8, 12)}-${s.slice(12, 16)}-${s.slice(16, 20)}-${s.slice(20, 32)}`;
}

/* --------------------------------------------------- public API */

export interface RunInput {
  ctx: AgentContext;
  /** Prior conversation turns, in order. Server prepends its own system
   *  prompt — do not include one here. */
  messages: Array<{ role: "user" | "assistant" | "model"; content: string }>;
  /** Override the provider's default model for this turn. */
  model?: string;
  /** Inject a specific provider (tests). Defaults to the env-configured
   *  active provider. The reliability layer still adds a fallback when
   *  available — pass `providerPool` to override that too. */
  provider?: AIProvider;
  /** F8 — explicit provider pool (primary first, fallback optional).
   *  Takes precedence over `provider`. Tests use this to inject mocks. */
  providerPool?: AIProvider[];
  /** F6 — client-generated conversation id. Enables server-side context
   *  (follow-ups, entity references). Omit → stateless one-shot. */
  conversationId?: string;
  /** F8 — server-generated correlation id, threaded into telemetry + logs.
   *  Generated by the route; tests may pass a known value. */
  requestId?: string;
  /** F8 — absolute wall-clock deadline (ms since epoch). Reliability layer
   *  stops new attempts past this point. Default: no deadline. */
  deadlineAt?: number;
}

export interface ProviderAttemptSummary {
  provider: string;
  model: string;
  durationMs: number;
  result:
    | "success"
    | "rate_limit"
    | "overloaded"
    | "timeout"
    | "tool_use_failed"
    | "invalid_request"
    | "auth"
    | "network"
    | "server"
    | "unknown";
}

export interface RunDebug {
  requestId: string;
  roundsUsed: number;
  toolsCalled: string[];
  localeMatched: boolean;
  provider: string;
  model: string;
  /** F8 — bounded retry + fallback telemetry. */
  providerAttempts: ProviderAttemptSummary[];
  retryCount: number;
  fallbackUsed: boolean;
  /** F6 — whether a conversation context was loaded/saved this turn. */
  contextActive: boolean;
  /** F6 — resolver verdict for the latest user message, if any was detected. */
  referenceResolved?: {
    kind: "resolved" | "ambiguous" | "unresolved";
    entityId?: string;
    reason: string;
  };
}

export async function runAgent(
  input: RunInput,
): Promise<{ response: AgentResponse; debug: RunDebug }> {
  const { ctx: baseCtx, messages, model: requestedModel } = input;
  // F10.0 — thread conversationId into AgentContext so tools (find_last_operation,
  // preview_rollback) can scope operation lookups to this chat.
  const ctx = {
    ...baseCtx,
    conversationId: input.conversationId ?? null,
  };

  // F8 — resolve provider pool (primary + optional fallback). Tests may inject
  // a specific pool; the route uses the env-configured primary + its opposite.
  const pool: AIProvider[] =
    input.providerPool && input.providerPool.length > 0
      ? input.providerPool
      : input.provider
        ? buildProviderPool({
            primary: input.provider,
            secondary: getFallbackProvider(input.provider.name),
          })
        : (() => {
            const primary = getActiveProvider();
            return buildProviderPool({
              primary,
              secondary: getFallbackProvider(primary.name),
            });
          })();
  const primary = pool[0]!;
  const model = requestedModel ?? primary.defaultModel;
  const locale: Locale = ctx.locale;

  // F8 — start the structured run record. Finishes on exit (success OR throw).
  const runRecord: AiRunRecord = startRun({
    requestId: input.requestId,
    conversationId: input.conversationId ?? null,
    tenantId: ctx.tenantId,
    userId: ctx.userId,
    branchId: null,
    locale,
  });

  // F11 — one logical assistant turn gets exactly one id. Minted server-side
  // at the start of the request; every internal event (tool calls, agent
  // rounds, provider retries, provider fallbacks, future stream chunks)
  // belongs to this id. Mobile adopts it as the AssistantMessage identity so
  // double-delivery cannot visually duplicate the response.
  const turnId = mintTurnId();

  // F11 ONE-TURN FAST PATH — trivial greetings/thanks/acks short-circuit the
  // full agent loop. This is pure (no DB, no provider, no I/O), returns ONE
  // text block in the locked locale, and keeps the invariant
  //   one user turn → one logical assistant turn
  // holding across the easiest regression cases ("Hi", "مرحبا", "thanks", …).
  // Every other turn still goes through the normal agent, so this cannot
  // mask a bug in the main pipeline.
  const latestUserText =
    [...messages].reverse().find((m) => m.role === "user")?.content ?? "";
  const fastHit = tryTrivialFastPath(latestUserText, locale);
  // F11 DIAGNOSTIC — the fast-path decision log is useful during dev but
  // echoes up to 80 chars of raw user text, which is tenant data in prod.
  // Gated behind STORO_AI_DEBUG so staging/development keep the signal and
  // production stays quiet. The structured `[ai/run]` record emitted at the
  // end of the turn already carries requestId + roundsUsed + toolCalls, so
  // operators don't lose correlation.
  if (process.env.STORO_AI_DEBUG === "1") {
    console.log(
      "[ai/agent] fast-path decision",
      JSON.stringify({
        requestId: runRecord.requestId,
        turnId,
        locale,
        latestUserText: latestUserText.slice(0, 80),
        latestUserTextLen: latestUserText.length,
        messagesLen: messages.length,
        fastHit: fastHit ? fastHit.kind : null,
      }),
    );
  }
  if (fastHit) {
    const blocks: AiBlock[] = [{ kind: "text", text: fastHit.text }];
    runRecord.roundsUsed = 0;
    runRecord.blockCount = 1;
    runRecord.blockKinds = ["text"];
    runRecord.contextActive = false;
    runRecord.usage = { promptTokens: 0, completionTokens: 0, totalTokens: 0 };
    runRecord.completion = "success";
    runRecord.finalResponseKind = "fast_path";
    finishRun(runRecord);
    return {
      response: {
        blocks,
        locale,
        model,
        usage: { promptTokens: 0, completionTokens: 0, totalTokens: 0 },
        toolsCalled: [],
        turnId,
      },
      debug: {
        requestId: runRecord.requestId,
        roundsUsed: 0,
        toolsCalled: [],
        localeMatched: true,
        provider: "fast_path",
        model,
        providerAttempts: [],
        retryCount: 0,
        fallbackUsed: false,
        contextActive: false,
        referenceResolved: undefined,
      },
    };
  }

  // F6 — load or create conversation context. Redis-backed; a null return
  // (no stored row, or Redis unavailable) degrades gracefully to a per-turn
  // stateless agent. Writes remain safe either way because the F5 preview →
  // confirm path is independent of context.
  const conversationContext: ConversationContext | null = input.conversationId
    ? (await loadContext({ tenantId: ctx.tenantId, conversationId: input.conversationId })) ??
      makeEmptyContext({
        tenantId: ctx.tenantId,
        userId: ctx.userId,
        conversationId: input.conversationId,
        branchId: null,
        locale,
      })
    : null;

  let referenceResolved: RunDebug["referenceResolved"] | undefined;
  if (conversationContext) {
    bumpTurn(conversationContext);
    const latestUser = [...messages].reverse().find((m) => m.role === "user")?.content ?? "";
    if (latestUser) {
      const r = resolveReference({
        userText: latestUser,
        context: conversationContext,
        currentBranchId: null,
      });
      referenceResolved =
        r.kind === "resolved"
          ? { kind: "resolved", entityId: r.entity.entityId, reason: r.reason }
          : { kind: r.kind, reason: r.reason };
    }
  }

  const conversation: ChatMessage[] = messages.map(
    (m): ChatMessage => ({
      role: m.role === "model" ? "assistant" : m.role,
      content: m.content,
    }),
  );

  const renderedBlocks: AiBlock[] = [];
  const toolsCalled: string[] = [];
  const groundingIndex: ToolResultIndex = emptyIndex();
  let roundsUsed = 0;
  let totalUsage = { promptTokens: 0, completionTokens: 0, totalTokens: 0 };

  try {
  for (let round = 0; round < MAX_ROUNDS; round++) {
    roundsUsed = round + 1;

    // From round 2 onward: re-assert the locale lock. Tool JSON (English keys,
    // English numbers) can nudge the model out of Arabic; a cheap system
    // reminder keeps it on policy.
    //
    // CRITICAL: only re-assert BEFORE any blocks have been rendered. Trace
    // from production ("هاااي" → roundsUsed: 5): once render_text produced
    // a block, the next round's re-asserted directive prompted the model
    // to answer it (treating the system reminder as a user question) with
    // another render_text call ("Understood. All responses will be
    // provided in Arabic…"), repeated across every subsequent round.
    if (round > 0 && renderedBlocks.length === 0) {
      conversation.push({
        role: "system",
        content: localeDirective(locale),
      });
    }

    const res = await callWithReliability({
      providers: pool,
      telemetry: runRecord,
      deadlineAt: input.deadlineAt,
      request: {
        system: baseSystemPrompt(ctx, locale, conversationContext, referenceResolved),
        messages: conversation,
        tools: toolDefinitions(),
        model,
        maxTokens: 3000,
        temperature: 0.2,
        reasoningEffort: "low",
        timeoutMs: 30_000,
      },
    });

    totalUsage = {
      promptTokens: totalUsage.promptTokens + res.usage.promptTokens,
      completionTokens: totalUsage.completionTokens + res.usage.completionTokens,
      totalTokens: totalUsage.totalTokens + res.usage.totalTokens,
    };

    conversation.push({
      role: "assistant",
      content: res.content,
      toolCalls: res.toolCalls.length > 0 ? res.toolCalls : undefined,
    });

    // No tool calls → final answer, OR a nudge-worthy "I forgot to render" state.
    if (res.toolCalls.length === 0) {
      const content = res.content;
      const dataToolFired = toolsCalled.some((n) => !isRenderTool(n));
      const canSalvage = /render_(text|chart|table|kpi|product_card|clarification|comparison|inventory_summary|sales_summary|warning|knowledge_answer)|preview_(update_product_price|update_product_quantity|create_customer)|search_knowledge/.test(content);
      const rendersAlready = renderedBlocks.length > 0;
      const canStillLoop = round < MAX_ROUNDS - 1;
      if (dataToolFired && !rendersAlready && !canSalvage && canStillLoop) {
        conversation.push({
          role: "system",
          content: localeDirective(locale) + "\n" + tr("nudge.renderMissing", locale),
        });
        continue;
      }
      // F9 — if search_knowledge fired with HIGH/MEDIUM hits but the agent
      // reached for render_text instead of render_knowledge_answer, nudge
      // once. This catches the EN/common-case where the model paraphrases
      // the answer in plain text and loses citations.
      const knowledgeAlreadyCited = renderedBlocks.some((b) => b.kind === "knowledge_answer");
      const knowledgeToolCalled = toolsCalled.includes("search_knowledge");
      const knowledgeHadHits = knowledgeToolCalled && groundingIndex.knowledgeChunks.size > 0;
      const knowledgeHadStrongTier = Array.from(groundingIndex.knowledgeChunks.values()).some(
        (c) => c.tier === "HIGH" || c.tier === "MEDIUM",
      );
      if (
        knowledgeToolCalled &&
        knowledgeHadHits &&
        knowledgeHadStrongTier &&
        !knowledgeAlreadyCited &&
        canStillLoop
      ) {
        const chunkIdsPreview = Array.from(groundingIndex.knowledgeChunks.keys()).slice(0, 3);
        conversation.push({
          role: "system",
          content:
            localeDirective(locale) +
            "\nsearch_knowledge returned HIGH/MEDIUM hits but you answered with render_text. " +
            "Re-answer the SAME policy question by calling render_knowledge_answer and cite the chunk_ids " +
            `from the earlier search_knowledge result (e.g. ${chunkIdsPreview.join(", ")}). ` +
            "Do NOT call search_knowledge again.",
        });
        continue;
      }
      const draftBlocks = await finalBlocks(renderedBlocks, content, locale);
      // F3: strip any product_card the model made up — guards against the
      // single most dangerous hallucination class (invented product/price).
      const groundedResult = enforceGrounding(draftBlocks, groundingIndex);
      // ONE-TURN INVARIANT — collapse multiple render_text calls into a
      // single text block so the user's turn renders as one visual response
      // instead of a stack of paragraph-bubbles. Structured blocks (cards,
      // tables, KPIs, confirmations, …) are preserved and stay in order.
      const blocks = collapseTurn(groundedResult.blocks);
      const report = groundedResult.report;
      const totalDrops =
        report.droppedProductCards.length +
        report.droppedClarifications.length +
        report.droppedComparisons.length +
        report.droppedClarificationOptions.length +
        report.droppedComparisonEntities.length +
        report.droppedKnowledgeCitations.length +
        report.droppedKnowledgeAnswers.length;
      if (totalDrops > 0) {
        recordGroundingDrop(runRecord, totalDrops);
        console.warn("[ai/agent] grounding drop", {
          requestId: runRecord.requestId,
          tenantId: ctx.tenantId,
          userId: ctx.userId,
          droppedProductCards: report.droppedProductCards,
          droppedClarifications: report.droppedClarifications,
          droppedClarificationOptions: report.droppedClarificationOptions,
          droppedComparisons: report.droppedComparisons,
          droppedComparisonEntities: report.droppedComparisonEntities,
          droppedKnowledgeCitations: report.droppedKnowledgeCitations,
          droppedKnowledgeAnswers: report.droppedKnowledgeAnswers,
        });
      }
      const localeMatched = blocks.every(
        (b) => b.kind !== "text" || replyMatchesLocale(b.text, locale),
      );
      if (!localeMatched) {
        recordLocaleDrift(runRecord);
        console.warn("[ai/agent] locale mismatch", {
          requestId: runRecord.requestId,
          tenantId: ctx.tenantId,
          userId: ctx.userId,
          locked: locale,
          provider: runRecord.finalProvider ?? pool[0]?.name,
          model,
        });
      }
      // F6 — persist context updates before returning. A Redis-write failure
      // only degrades follow-up resolution; the reply still goes to the user.
      if (conversationContext) {
        try {
          await saveContext(conversationContext);
        } catch (e) {
          recordRedisDegradation(runRecord, e instanceof Error ? e.message : "unknown");
        }
      }
      // F8 — finish the telemetry record (one structured log line).
      runRecord.roundsUsed = roundsUsed;
      runRecord.blockCount = blocks.length;
      runRecord.blockKinds = blocks.map((b) => b.kind);
      runRecord.contextActive = conversationContext !== null;
      runRecord.referenceResolution =
        referenceResolved ? referenceResolved.kind : null;
      runRecord.usage = { ...totalUsage };
      runRecord.completion = "success";
      runRecord.finalResponseKind = "blocks";
      finishRun(runRecord);

      return {
        response: {
          blocks,
          locale,
          model,
          usage: totalUsage,
          toolsCalled,
          turnId,
        },
        debug: {
          requestId: runRecord.requestId,
          roundsUsed,
          toolsCalled,
          localeMatched,
          provider: runRecord.finalProvider ?? pool[0]!.name,
          model,
          providerAttempts: runRecord.providerAttempts.map((a) => ({
            provider: a.provider,
            model: a.model,
            durationMs: a.durationMs,
            result: a.result,
          })),
          retryCount: runRecord.retryCount,
          fallbackUsed: runRecord.fallbackUsed,
          contextActive: conversationContext !== null,
          referenceResolved,
        },
      };
    }

    // Execute every tool call in parallel. Each call is individually timed
    // so the F8 metrics can distinguish between model latency, DB latency and
    // render latency without needing an APM.
    const results = await Promise.all(
      res.toolCalls.map(async (tc) => {
        toolsCalled.push(tc.name);
        const tStart = Date.now();
        const result = await executeTool(ctx, tc.name, tc.argsJson);
        recordToolCall(runRecord, {
          name: tc.name,
          durationMs: Date.now() - tStart,
          argBytes: tc.argsJson?.length ?? 0,
          ok: result.ok === true,
          errorKind: result.ok ? undefined : (result as { error: string }).error,
        });
        return { tc, result };
      }),
    );

    // Record every grounded id a data tool surfaced this turn — the grounding
    // guard uses this to drop any product_card the model invents.
    for (const { tc, result } of results) {
      if (!isRenderTool(tc.name) && result.ok && "data" in result) {
        indexToolResult(groundingIndex, result.data);
      }
    }

    // F6 — feed tool results into the conversation context store so the next
    // turn's ACTIVE CONTEXT block carries real database entities.
    if (conversationContext) {
      for (const { tc, result } of results) {
        captureToolResult(conversationContext, tc.name, result);
      }
    }

    for (const { tc, result } of results) {
      // Any tool whose success result carries `blocks` (render_* OR preview_*
      // staging a confirmation) buffers them into the final reply AND gets a
      // tiny ack tool message so the model doesn't see its own JSON echoed
      // back and try to "render" it again next round.
      //
      // mergeDedup is the ROOT-CAUSE guard for the duplicate-product-card bug:
      // if the model re-calls render_product_card for the same productId in a
      // later round (nudge, salvage, retry), the second card is silently
      // dropped. First occurrence wins, cap stays enforced.
      const blocks = blocksFromResult(result);
      if (blocks) {
        const merged = mergeDedup(renderedBlocks, blocks).slice(0, MAX_RENDER_BLOCKS);
        renderedBlocks.length = 0;
        renderedBlocks.push(...merged);
        conversation.push({
          role: "tool",
          toolCallId: tc.id,
          toolName: tc.name,
          content: JSON.stringify({ ok: true, rendered: true }),
        });
      } else {
        conversation.push({
          role: "tool",
          toolCallId: tc.id,
          toolName: tc.name,
          content: JSON.stringify(result),
        });
      }
    }

    // ONE-TURN EXIT GUARD. Real-world trace from the user ("هاااي" →
    // roundsUsed: 5): the model ran one render_text in round 1, then the
    // next 4 rounds it kept emitting more render_text calls echoing the
    // locale directive ("Understood. All responses will be provided in
    // Arabic. …"). Each round compounded the greeting with no new data.
    //
    // Rule: if EVERY tool call in this round was a presentation tool
    // (render_* / preview_*), and we already have blocks buffered, the
    // turn is complete. Any further round would only invite the model to
    // paraphrase itself. Exit the loop and let the "loop capped" return
    // path ship the buffered blocks.
    const allPresentational = res.toolCalls.every(
      (tc) => tc.name.startsWith("render_") || tc.name.startsWith("preview_"),
    );
    if (allPresentational && renderedBlocks.length > 0) {
      runRecord.roundsUsed = roundsUsed;
      break;
    }
  }

  // Loop capped. If we ALREADY rendered blocks, the user has a complete
  // answer — don't tag an apology onto it.
  const blocks: AiBlock[] = collapseTurn(
    renderedBlocks.length > 0
      ? renderedBlocks
      : [{ kind: "text", text: tr("nudge.capReached.content", locale) }],
  );
  if (conversationContext) {
    try {
      await saveContext(conversationContext);
    } catch (e) {
      recordRedisDegradation(runRecord, e instanceof Error ? e.message : "unknown");
    }
  }
  runRecord.roundsUsed = roundsUsed;
  runRecord.blockCount = blocks.length;
  runRecord.blockKinds = blocks.map((b) => b.kind);
  runRecord.contextActive = conversationContext !== null;
  runRecord.referenceResolution = referenceResolved ? referenceResolved.kind : null;
  runRecord.usage = { ...totalUsage };
  runRecord.completion = renderedBlocks.length > 0 ? "success" : "failure";
  runRecord.finalResponseKind = renderedBlocks.length > 0 ? "blocks" : "capped";
  finishRun(runRecord);
  return {
    response: {
      blocks,
      locale,
      model,
      usage: totalUsage,
      toolsCalled,
      turnId,
    },
    debug: {
      requestId: runRecord.requestId,
      roundsUsed,
      toolsCalled,
      localeMatched: true,
      provider: runRecord.finalProvider ?? pool[0]!.name,
      model,
      providerAttempts: runRecord.providerAttempts.map((a) => ({
        provider: a.provider,
        model: a.model,
        durationMs: a.durationMs,
        result: a.result,
      })),
      retryCount: runRecord.retryCount,
      fallbackUsed: runRecord.fallbackUsed,
      contextActive: conversationContext !== null,
      referenceResolved,
    },
  };
  } catch (err) {
    // F8 — provider pool exhausted (or other unexpected throw). Finalize the
    // telemetry record so metrics/logs aren't silently lost, then rethrow so
    // the route can convert this into a user-facing HTTP error.
    runRecord.roundsUsed = roundsUsed;
    runRecord.usage = { ...totalUsage };
    runRecord.completion = "failure";
    runRecord.finalResponseKind = classifyFinalResponseKind(err);
    runRecord.failureCategory = classifyFailureCategory(err);
    finishRun(runRecord);
    throw err;
  }
}

function classifyFinalResponseKind(err: unknown): import("./telemetry").FinalResponseKind {
  if (err instanceof ProviderError) {
    if (err.kind === "auth") return "auth_failed";
    if (err.kind === "invalid_request") return "invalid_request";
    return "provider_failed";
  }
  return "provider_failed";
}

function classifyFailureCategory(err: unknown): import("./telemetry").FailureCategory {
  if (err instanceof ProviderError) {
    switch (err.kind) {
      case "rate_limit": return "provider_rate_limit";
      case "overloaded": return "provider_overloaded";
      case "timeout": return "provider_timeout";
      case "network": return "provider_network";
      case "auth": return "provider_auth";
      case "invalid_request": return "provider_invalid_request";
      case "tool_use_failed": return "provider_tool_use_failed";
      case "server": return "provider_server";
      default: return "provider_unknown";
    }
  }
  return "unknown";
}

