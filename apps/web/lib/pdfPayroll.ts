/* ─────────────────────────── Font / logo cache ──────────────────────── */

let cachedFontBytes: Uint8Array | null = null;
async function loadCairo(): Promise<Uint8Array> {
  if (cachedFontBytes) return cachedFontBytes;
  const buf = await readFile(path.join(process.cwd(), "public", "fonts", "Cairo.ttf"));
  cachedFontBytes = new Uint8Array(buf);
  return cachedFontBytes;
}

let cachedLogoBytes: Uint8Array | null = null;
async function loadLogo(): Promise<Uint8Array | null> {
  if (cachedLogoBytes) return cachedLogoBytes;
  try {
    const buf = await readFile(path.join(process.cwd(), "public", "logo.png"));
    cachedLogoBytes = new Uint8Array(buf);
    return cachedLogoBytes;
  } catch {
    return null;
  }
}

/* ─────────────────────────── Formatters ─────────────────────────────── */

function fmtMoney(n: number, currency: string): string {
  const abs = Math.abs(n).toLocaleString("en-US", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return n < 0 ? `−${abs} ${currency}` : `${abs} ${currency}`;
}

function fmtInt(n: number): string {
  return n.toLocaleString("en-US");
}

function fmtMonth(iso: string, locale: PayrollPdfLocale): string {
  const d = new Date(iso);
  const y = d.getUTCFullYear();
  const m = d.getUTCMonth();
  const monthEn = [
    "January",
    "February",
    "March",
    "April",
    "May",
    "June",
    "July",
    "August",
    "September",
    "October",
    "November",
    "December",
  ][m];
  const monthAr = [
    "يناير",
    "فبراير",
    "مارس",
    "أبريل",
    "مايو",
    "يونيو",
    "يوليو",
    "أغسطس",
    "سبتمبر",
    "أكتوبر",
    "نوفمبر",
    "ديسمبر",
  ][m];
  return locale === "ar" ? `${monthAr} ${y}` : `${monthEn} ${y}`;
}

function fmtDate(iso: string | null): string {
  if (!iso) return "—";
  const d = new Date(iso);
  const pad = (x: number) => x.toString().padStart(2, "0");
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

function fitText(text: string, font: PDFFont, size: number, maxW: number): string {
  if (!text) return "";
  if (font.widthOfTextAtSize(text, size) <= maxW) return text;
  const ellipsis = "…";
  let lo = 0;
  let hi = text.length;
  while (lo < hi) {
    const mid = Math.ceil((lo + hi) / 2);
    const slice = text.slice(0, mid) + ellipsis;
    if (font.widthOfTextAtSize(slice, size) <= maxW) lo = mid;
    else hi = mid - 1;
  }
  return text.slice(0, lo) + ellipsis;
}

function lifecycleLabel(
  lc: PayrollLifecycle,
  L: typeof DICT.en | typeof DICT.ar,
): string {
  switch (lc) {
    case "DRAFT":
      return L.draft;
    case "FINALIZED":
      return L.finalized;
    case "VOIDED":
      return L.voided;
    default:
      return L.missing;
  }
}

/* ─────────────────────── Register (landscape A4) ─────────────────────── */

const A4L = { w: 841.89, h: 595.28 };
const A4P = { w: 595.28, h: 841.89 };
const MARGIN = 36;

export async function generatePayrollRegisterPdf(
  input: PayrollRegisterPdfInput,
): Promise<Uint8Array> {
  const currency = input.currency ?? "EGP";
  const locale: PayrollPdfLocale = input.locale ?? "en";
  const L = DICT[locale];

  const pdf = await PDFDocument.create();
  pdf.registerFontkit(fontkit);
  pdf.setTitle(input.filename.replace(/\.pdf$/i, ""));
  pdf.setCreator("Storo");
  pdf.setProducer("Storo · Payroll Register");

  const cairoBytes = await loadCairo();
  const body = await pdf.embedFont(cairoBytes, { subset: true });
  await pdf.embedFont(StandardFonts.Courier); // reserved

  const TEXT = rgb(0.078, 0.102, 0.141);
  const MUTED = rgb(0.45, 0.48, 0.55);
  const BORDER = rgb(0.88, 0.89, 0.92);
  const BG_TINT = rgb(0.96, 0.97, 0.99);

  let page: PDFPage = pdf.addPage([A4L.w, A4L.h]);

  // Columns (register). Widths sum to A4L.w - 2*MARGIN = 769.89.
  const cols = [
    { key: "employee", label: L.employee, w: 160, align: "left" as const },
    { key: "status", label: L.status, w: 70, align: "center" as const },
    { key: "base", label: L.base, w: 70, align: "right" as const },
    { key: "hourly", label: L.hourly, w: 70, align: "right" as const },
    { key: "overtime", label: L.overtime, w: 70, align: "right" as const },
    { key: "sales", label: L.sales, w: 80, align: "right" as const },
    { key: "commission", label: L.commission, w: 80, align: "right" as const },
    { key: "bonus", label: L.bonus, w: 65, align: "right" as const },
    { key: "deductions", label: L.deductions, w: 65, align: "right" as const },
    { key: "net", label: L.net, w: 85, align: "right" as const },
  ];

  const colX = (i: number): number => {
    let x = MARGIN;
    for (let k = 0; k < i; k++) x += cols[k]!.w;
    return x;
  };

  // Header band — store identity + period
  const logo = await loadLogo();
  let y = A4L.h - MARGIN;
  if (logo) {
    const image = await pdf.embedPng(logo);
    const h = 28;
    const w = (image.width * h) / image.height;
    page.drawImage(image, { x: MARGIN, y: y - h, width: w, height: h });
  }
  page.drawText(input.shopName, {
    x: MARGIN + (logo ? 36 : 0),
    y: y - 10,
    size: 14,
    font: body,
    color: TEXT,
  });
  page.drawText(`${L.registerTitle} · ${L.period}: ${fmtMonth(input.periodStart, locale)}`, {
    x: MARGIN + (logo ? 36 : 0),
    y: y - 26,
    size: 10,
    font: body,
    color: MUTED,
  });
  y -= 46;

  // Column headers
  page.drawRectangle({
    x: MARGIN,
    y: y - 18,
    width: A4L.w - 2 * MARGIN,
    height: 18,
    color: BG_TINT,
  });
  for (let i = 0; i < cols.length; i++) {
    const c = cols[i]!;
    const text = fitText(c.label, body, 9, c.w - 6);
    const tw = body.widthOfTextAtSize(text, 9);
    let tx = colX(i) + 3;
    if (c.align === "right") tx = colX(i) + c.w - 3 - tw;
    else if (c.align === "center") tx = colX(i) + (c.w - tw) / 2;
    page.drawText(text, { x: tx, y: y - 13, size: 9, font: body, color: TEXT });
  }
  y -= 22;

  const rowH = 16;

  // Totals accumulator.
  let totalBase = 0;
  let totalHourly = 0;
  let totalOT = 0;
  let totalSales = 0;
  let totalCommission = 0;
  let totalBonus = 0;
  let totalDed = 0;
  let totalNet = 0;

  if (input.rows.length === 0) {
    page.drawText(L.noData, { x: MARGIN, y, size: 10, font: body, color: MUTED });
    y -= 20;
  }

  for (const row of input.rows) {
    if (y - rowH < MARGIN + 40) {
      // New page
      page = pdf.addPage([A4L.w, A4L.h]);
      y = A4L.h - MARGIN;
    }
    const s = row.snapshot;
    const pos = Math.max(0, s.adjustmentsTotal);
    // adjustments can be signed; split into bonus + deductions by iterating.
    let bonusPart = 0;
    let dedPart = 0;
    for (const a of s.adjustments) {
      if (a.amount >= 0) bonusPart += a.amount;
      else dedPart += a.amount;
    }
    // Fallback if `adjustments` array is empty (older rows) but
    // adjustmentsTotal has a value — keep it under "bonus" for display.
    if (s.adjustments.length === 0 && s.adjustmentsTotal !== 0) {
      if (s.adjustmentsTotal >= 0) bonusPart = s.adjustmentsTotal;
      else dedPart = s.adjustmentsTotal;
    }
    const sales = s.commissionGrossSales;

    totalBase += s.baseEarnings;
    totalHourly += s.hourlyEarnings;
    // Overtime hours multiplied by hourly piece is already in hourlyEarnings
    // for pure-hourly comp or the hybrid branch. We surface the hours, not a
    // separate pay bucket, to avoid double-counting.
    totalOT += s.overtimeHours;
    totalSales += sales;
    totalCommission += s.commissionAmount;
    totalBonus += bonusPart;
    totalDed += dedPart;
    totalNet += s.netAmount;

    const cells = [
      row.employeeName ?? row.employeeId.slice(0, 8),
      lifecycleLabel(row.lifecycle, L),
      fmtMoney(s.baseEarnings, currency),
      fmtMoney(s.hourlyEarnings, currency),
      `${fmtInt(s.overtimeHours)} h`,
      fmtMoney(sales, currency),
      fmtMoney(s.commissionAmount, currency),
      fmtMoney(bonusPart, currency),
      fmtMoney(dedPart, currency),
      fmtMoney(s.netAmount, currency),
    ];
    for (let i = 0; i < cols.length; i++) {
      const c = cols[i]!;
      const text = fitText(cells[i]!, body, 9, c.w - 6);
      const tw = body.widthOfTextAtSize(text, 9);
      let tx = colX(i) + 3;
      if (c.align === "right") tx = colX(i) + c.w - 3 - tw;
      else if (c.align === "center") tx = colX(i) + (c.w - tw) / 2;
      const color = row.lifecycle === "VOIDED" ? MUTED : TEXT;
      page.drawText(text, { x: tx, y: y - 11, size: 9, font: body, color });
    }
    page.drawLine({
      start: { x: MARGIN, y: y - rowH },
      end: { x: A4L.w - MARGIN, y: y - rowH },
      thickness: 0.4,
      color: BORDER,
    });
    y -= rowH;
    void pos; // silence unused
  }

  // Totals row
  if (y - 24 < MARGIN) {
    page = pdf.addPage([A4L.w, A4L.h]);
    y = A4L.h - MARGIN;
  }
  page.drawRectangle({
    x: MARGIN,
    y: y - 20,
    width: A4L.w - 2 * MARGIN,
    height: 20,
    color: BG_TINT,
  });
  const totalsCells = [
    L.totals,
    "",
    fmtMoney(totalBase, currency),
    fmtMoney(totalHourly, currency),
    `${fmtInt(totalOT)} h`,
    fmtMoney(totalSales, currency),
    fmtMoney(totalCommission, currency),
    fmtMoney(totalBonus, currency),
    fmtMoney(totalDed, currency),
    fmtMoney(totalNet, currency),
  ];
  for (let i = 0; i < cols.length; i++) {
    const c = cols[i]!;
    const text = fitText(totalsCells[i]!, body, 10, c.w - 6);
    const tw = body.widthOfTextAtSize(text, 10);
    let tx = colX(i) + 3;
    if (c.align === "right") tx = colX(i) + c.w - 3 - tw;
    else if (c.align === "center") tx = colX(i) + (c.w - tw) / 2;
    page.drawText(text, { x: tx, y: y - 14, size: 10, font: body, color: TEXT });
  }

  // Footer
  page.drawText(L.generatedByStoro, {
    x: MARGIN,
    y: MARGIN - 8,
    size: 8,
    font: body,
    color: MUTED,
  });

  return pdf.save();
}

/* ───────────────────────── Statement (portrait A4) ───────────────────── */

export async function generatePayrollStatementPdf(
  input: PayrollStatementPdfInput,
): Promise<Uint8Array> {
  const currency = input.currency ?? "EGP";
  const locale: PayrollPdfLocale = input.locale ?? "en";
  const L = DICT[locale];

  const pdf = await PDFDocument.create();
  pdf.registerFontkit(fontkit);
  pdf.setTitle(input.filename.replace(/\.pdf$/i, ""));
  pdf.setCreator("Storo");
  pdf.setProducer("Storo · Payroll Statement");

  const cairoBytes = await loadCairo();
  const body = await pdf.embedFont(cairoBytes, { subset: true });

  const TEXT = rgb(0.078, 0.102, 0.141);
  const MUTED = rgb(0.45, 0.48, 0.55);
  const BORDER = rgb(0.88, 0.89, 0.92);
  const BG_TINT = rgb(0.96, 0.97, 0.99);

  let page: PDFPage = pdf.addPage([A4P.w, A4P.h]);
  const sheet = input.sheet;
  const s = sheet.snapshot;
  const comp = sheet.compensationSnapshot;

  const logo = await loadLogo();
  let y = A4P.h - MARGIN;
  if (logo) {
    const image = await pdf.embedPng(logo);
    const h = 28;
    const w = (image.width * h) / image.height;
    page.drawImage(image, { x: MARGIN, y: y - h, width: w, height: h });
  }
  page.drawText(input.shopName, {
    x: MARGIN + (logo ? 36 : 0),
    y: y - 10,
    size: 14,
    font: body,
    color: TEXT,
  });
  page.drawText(`${L.statementTitle} · ${fmtMonth(sheet.periodStart, locale)}`, {
    x: MARGIN + (logo ? 36 : 0),
    y: y - 26,
    size: 10,
    font: body,
    color: MUTED,
  });
  y -= 50;

  // Employee / Status card
  page.drawRectangle({
    x: MARGIN,
    y: y - 60,
    width: A4P.w - 2 * MARGIN,
    height: 60,
    color: BG_TINT,
  });
  page.drawText(`${L.employee}:`, { x: MARGIN + 10, y: y - 16, size: 9, font: body, color: MUTED });
  page.drawText(sheet.employeeName ?? sheet.employeeId.slice(0, 8), {
    x: MARGIN + 10,
    y: y - 30,
    size: 13,
    font: body,
    color: TEXT,
  });
  page.drawText(`${L.status}:`, { x: A4P.w / 2, y: y - 16, size: 9, font: body, color: MUTED });
  page.drawText(lifecycleLabel(sheet.lifecycle, L), {
    x: A4P.w / 2,
    y: y - 30,
    size: 13,
    font: body,
    color: sheet.lifecycle === "VOIDED" ? MUTED : TEXT,
  });
  if (sheet.finalizedAt) {
    page.drawText(`${L.finalizedOn} ${fmtDate(sheet.finalizedAt)}`, {
      x: MARGIN + 10,
      y: y - 48,
      size: 8,
      font: body,
      color: MUTED,
    });
  }
  y -= 80;

  const section = (title: string) => {
    page.drawText(title, { x: MARGIN, y, size: 11, font: body, color: TEXT });
    page.drawLine({
      start: { x: MARGIN, y: y - 3 },
      end: { x: A4P.w - MARGIN, y: y - 3 },
      thickness: 0.5,
      color: BORDER,
    });
    y -= 16;
  };

  const kv = (key: string, value: string, highlight = false) => {
    if (y < MARGIN + 60) {
      page = pdf.addPage([A4P.w, A4P.h]);
      y = A4P.h - MARGIN;
    }
    page.drawText(key, { x: MARGIN, y, size: 10, font: body, color: MUTED });
    const tw = body.widthOfTextAtSize(value, highlight ? 12 : 10);
    page.drawText(value, {
      x: A4P.w - MARGIN - tw,
      y,
      size: highlight ? 12 : 10,
      font: body,
      color: TEXT,
    });
    y -= highlight ? 18 : 14;
  };

  // Compensation
  section(L.compensation);
  if (comp) {
    const payTypeLabel = {
      fixed: L.payTypeFixed,
      hourly: L.payTypeHourly,
      hybrid: L.payTypeHybrid,
    }[comp.payType];
    kv("Pay type", payTypeLabel);
    if (comp.baseSalaryMonthly != null)
      kv(L.base, fmtMoney(comp.baseSalaryMonthly, currency));
    if (comp.hourlyRate != null)
      kv("Rate / h", fmtMoney(comp.hourlyRate, currency));
    if (comp.commissionRate > 0) kv(L.commission, `${comp.commissionRate}%`);
  } else {
    page.drawText("—", { x: MARGIN, y, size: 10, font: body, color: MUTED });
    y -= 14;
  }
  y -= 10;

  // Attendance + leave
  section(L.attendance);
  kv(L.regularHours, fmtInt(s.regularHours));
  kv(L.overtimeHours, fmtInt(s.overtimeHours));
  if (s.paidLeaveDays > 0) kv(L.paidLeaveDays, fmtInt(s.paidLeaveDays));
  if (s.unpaidLeaveDays > 0) kv(L.unpaidLeaveDays, fmtInt(s.unpaidLeaveDays));
  y -= 10;

  // Earnings
  section(L.gross);
  if (s.baseEarnings > 0) kv(L.base, fmtMoney(s.baseEarnings, currency));
  if (s.hourlyEarnings > 0) kv(L.hourly, fmtMoney(s.hourlyEarnings, currency));
  if (s.commissionGrossSales > 0) {
    kv(L.sales, fmtMoney(s.commissionGrossSales, currency));
    kv(L.commission, fmtMoney(s.commissionAmount, currency));
  }
  kv(L.gross, fmtMoney(s.grossAmount + s.commissionAmount, currency), true);
  y -= 10;

  // Adjustments
  section(L.adjustmentsHeading);
  if (s.adjustments.length === 0) {
    page.drawText(L.emptyAdjustments, { x: MARGIN, y, size: 10, font: body, color: MUTED });
    y -= 14;
  } else {
    for (const a of s.adjustments) {
      const sign = a.amount < 0 ? "−" : "+";
      const label = a.reason ? `${a.kind} (${a.reason})` : a.kind;
      kv(label, `${sign}${Math.abs(a.amount).toLocaleString("en-US", { minimumFractionDigits: 2 })} ${currency}`);
    }
    kv(L.totals, fmtMoney(s.adjustmentsTotal, currency), true);
  }
  y -= 10;

  // Net
  section(L.net);
  kv(L.net, fmtMoney(s.netAmount, currency), true);

  // Warnings
  if (s.warnings.length > 0) {
    y -= 10;
    section(L.warningsLabel);
    for (const w of s.warnings) {
      if (y < MARGIN + 20) {
        page = pdf.addPage([A4P.w, A4P.h]);
        y = A4P.h - MARGIN;
      }
      page.drawText(`• ${w.message}`, { x: MARGIN, y, size: 9, font: body, color: MUTED });
      y -= 12;
    }
  }

  page.drawText(L.generatedByStoro, {
    x: MARGIN,
    y: MARGIN - 8,
    size: 8,
    font: body,
    color: MUTED,
  });

  return pdf.save();
}
